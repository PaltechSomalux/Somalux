export const PROFICIENCY_LEVELS = [
  'Native',
  'Fluent',
  'Professional',
  'Intermediate',
  'Basic',
  'Learning',
];

// Get all available languages
export const getLanguages = () => {
  return [...new Set(LANGUAGES)].sort();
};

// Get proficiency levels
export const getProficiencyLevels = () => {
  return PROFICIENCY_LEVELS;
};

// Format language with proficiency
export const formatLanguage = (language, proficiency) => {
  if (!language) return '';
  if (!proficiency) return language;
  return `${language} (${proficiency})`;
};

// Parse language string back to components
export const parseLanguage = (languageString) => {
  if (!languageString) return { language: '', proficiency: '' };
  
  const match = languageString.match(/^(.+?)\s*\(([^)]+)\)$/);
  if (match) {
    return {
      language: match[1].trim(),
      proficiency: match[2].trim(),
    };
  }
  
  return { language: languageString.trim(), proficiency: '' };
};
